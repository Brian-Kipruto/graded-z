"""
macros.py — turn a config dict into a Geant4 .mac file.

This is the Python side of the macro-language contract (Architecture Lockdown
interface #1). The vocabulary here must stay in lockstep with DetectorMessenger:
if you emit a command the Messenger doesn't understand, the run fails.

One config → one directory → one config.mac + (later) output.csv + stdout.log.
"""
from __future__ import annotations
from pathlib import Path
from typing import Dict

from . import config as C


def macro_for_config(cfg: Dict, run_dir: Path, seed: int) -> str:
    """Return the full text of the .mac file for one configuration."""
    lines = []
    lines.append("# Auto-generated by orchestrator. Do not edit by hand.")
    lines.append(f"# config_id = {cfg['config_id']}")
    lines.append("")
    lines.append("/run/initialize")
    lines.append("")

    # Reproducible, UNIQUE seed per run (pitfall: identical seeds → identical runs).
    lines.append(f"/random/setSeeds {seed} {seed + 1}")
    lines.append("")

    # Geometry: clear → addLayer×N → setSourceDistance → build.
    lines.append("/shield/clearLayers")
    for layer in cfg["layers"]:
        lines.append(
            f"/shield/addLayer {layer['material']} {layer['thickness_mm']} mm"
        )
    lines.append(f"/shield/setSourceDistance {cfg['source_distance_mm']} mm")
    lines.append("/shield/build")
    lines.append("")

    # Source.
    lines.append("/control/execute source_ambe.mac")
    lines.append("")

    # Output file for THIS run, written inside its own directory.
    # G4AnalysisManager appends ".csv". We use a path without extension.
    out_base = (run_dir / "output").as_posix()
    lines.append(f"/analysis/setFileName {out_base}")
    lines.append("")

    # Run.
    lines.append(f"/run/printProgress {max(1, C.EVENTS_PER_RUN // 5)}")
    lines.append(f"/run/beamOn {C.EVENTS_PER_RUN}")
    lines.append("")

    return "\n".join(lines)


def write_macro(cfg: Dict, run_dir: Path, seed: int) -> Path:
    """Write config.mac into run_dir and return its path."""
    run_dir.mkdir(parents=True, exist_ok=True)
    mac_path = run_dir / "config.mac"
    mac_path.write_text(macro_for_config(cfg, run_dir, seed))
    return mac_path
